// Adding a to-do on the To-do page: a section's add line read as you type ("essay 3h due fri"), its chips that set
// each field yourself (kind, tag, due, length, repeat), the question when there's no due date, Shift-Enter from any
// field, Escape, the Long term list and the AI fallback for a line the grammar can't read.
import { configure, screen, waitFor, within } from "@testing-library/react"
import { describe, expect, it } from "vitest"
import { friday, openFriday, waitForSent } from "@/test/friday"

// A real server, replanning after each change: a moment longer than the default second to answer.
configure({ asyncUtilTimeout: 5000 })

const TIP = ": click for everything about it, double-click the title to rename"
const row = (title: string) => screen.findByTitle(`${title}${TIP}`, {}, { timeout: 10_000 })
/** The page once its list has loaded: an add sent before that is read over by the list's first answer. */
async function todo(route = "/todo") {
  const f = await openFriday(route)
  await screen.findAllByRole("checkbox", { name: "Mark done" }, { timeout: 10_000 }).catch(() => null)
  return f
}
/** A chip under the line, by what it's for. */
const chip = (tip: string) => screen.getByTitle(tip)
/** The open chip's panel, by its tip. */
const panel = (tip: string) => screen.getByText(tip, { selector: "span" }).parentElement as HTMLElement

describe("the add line", () => {
  it("reads a line as you type it, fills in its section's kind, and adds it on Enter", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add an assignment…")
    await user.type(line, "essay 3h due fri")
    expect(screen.getByText("↵ add · ⇧↵ from any field")).toBeTruthy()
    await waitFor(() => expect(chip("How long it takes").textContent).toBe("3h"))
    expect(chip("What sort of work").textContent).toBe("Assignment")
    await waitFor(() => expect(chip("When it's due").textContent).toMatch(/^Due Fri/))
    expect(chip("How often it comes back").textContent).toBe("Once")
    expect(chip("What it belongs to").textContent).toBe("No tag")
    // With a due, whether there's time for it shows by itself.
    expect(await screen.findByText(/Checking whether you have time…|fits|late|tight|time/i)).toBeTruthy()
    await user.keyboard("{Enter}")
    const sent = await waitForSent("add")
    expect(sent.body).toEqual({ text: "essay 3h due fri", preset: "Assignment" })
    const added = await row("essay")
    expect(within(added).getByText("new")).toBeTruthy()
    expect((line as HTMLInputElement).value).toBe("")
  })

  it("asks first when there's no due date, and Yes adds it as it is", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add an errand…")
    await user.type(line, "return library books{Enter}")
    const ask = await screen.findByRole("group", { name: "No due date" })
    expect(within(ask).getByText("No due date. Add it anyway?")).toBeTruthy()
    await user.click(within(ask).getByRole("button", { name: /Yes, add/ }))
    const sent = await waitForSent("add")
    expect(sent.body).toEqual({ text: "return library books", preset: "Errand" })
    expect(await row("return library books")).toBeTruthy()
  })

  it("takes the due typed in the question, and Cancel or typing on closes it", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add an errand…")
    await user.type(line, "mail postcard{Enter}")
    let ask = await screen.findByRole("group", { name: "No due date" })
    await user.click(within(ask).getByRole("button", { name: "Cancel" }))
    expect(screen.queryByRole("group", { name: "No due date" })).toBeNull()
    await user.type(line, "{Enter}")
    await screen.findByRole("group", { name: "No due date" })
    await user.type(line, "s")
    expect(screen.queryByRole("group", { name: "No due date" })).toBeNull()
    await user.type(line, "{Enter}")
    ask = await screen.findByRole("group", { name: "No due date" })
    await user.type(within(ask).getByRole("textbox", { name: "Due" }), "tomorrow{Enter}")
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ text: "mail postcards", preset: "Errand", due: expect.stringMatching(/T23:59$/) })
  })

  it("adds without a due when Enter is pressed again in the question", async () => {
    const { user } = await todo()
    await user.type(screen.getByLabelText("Add anything else…"), "tidy desk{Enter}")
    const ask = await screen.findByRole("group", { name: "No due date" })
    await user.type(within(ask).getByRole("textbox", { name: "Due" }), "{Enter}")
    expect((await waitForSent("add")).body).toEqual({ text: "tidy desk" })
  })

  it("sets the kind, the tag and the due from their chips, each pinned, and Shift-Enter adds it", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add anything else…")
    await user.type(line, "rocket fins")
    await user.click(chip("What sort of work"))
    await user.click(within(panel("What sort of work")).getByRole("button", { name: "Errand" }))
    expect(chip("What sort of work").textContent).toBe("Errand")
    await user.click(chip("What it belongs to"))
    await user.click(within(panel("What it belongs to")).getByRole("button", { name: "Rocketry" }))
    expect(chip("What it belongs to").textContent).toBe("Rocketry")
    await user.click(chip("When it's due"))
    await user.click(within(panel("When it's due")).getByRole("button", { name: "In a week" }))
    expect(chip("When it's due").textContent).toMatch(/^Due /)
    // A second click on a chip closes its panel.
    await user.click(chip("How often it comes back"))
    expect(screen.getByText("Once.")).toBeTruthy()
    await user.click(chip("How often it comes back"))
    expect(screen.queryByText("Once.")).toBeNull()
    await user.keyboard("{Shift>}{Enter}{/Shift}")
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ text: "rocket fins", preset: "Errand", area: "Rocketry", due: expect.stringMatching(/T23:59$/) })
  })

  it("sets the length from its chip: a quick pick, one typed, a short one, or Friday's guess", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add anything else…")
    await user.type(line, "stretch due tomorrow")
    await user.click(chip("How long it takes"))
    const lengths = panel("How long it takes")
    expect(within(lengths).getByText("Friday decides", { selector: "span" })).toBeTruthy()
    await user.click(within(lengths).getByRole("button", { name: "5m" }))
    expect(within(lengths).getByText("Planned in a 15-minute slot, the smallest Friday places.")).toBeTruthy()
    await user.click(within(lengths).getByRole("button", { name: "2h" }))
    expect(chip("How long it takes").textContent).toBe("2h")
    const typed = within(lengths).getByRole("textbox", { name: "Length" })
    await user.clear(typed)
    await user.type(typed, "nonsense")
    expect(within(lengths).getByText("Can't read that as a length")).toBeTruthy()
    expect(typed.getAttribute("aria-invalid")).toBe("true")
    await user.clear(typed)
    await user.type(typed, "45{Enter}")
    expect(chip("How long it takes").textContent).toBe("45m")
    await user.click(within(lengths).getByRole("button", { name: "Friday decides" }))
    await user.click(within(lengths).getByRole("button", { name: "30m" }))
    // Shift-Enter from inside the panel adds it too.
    within(lengths).getByRole("textbox", { name: "Length" }).focus()
    await user.keyboard("{Shift>}{Enter}{/Shift}")
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ text: "stretch due tomorrow", duration_min: 30 })
  })

  it("sets how often it comes back: quick picks, chosen days, times a week, and when it ends", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add anything else…")
    await user.type(line, "water plants")
    await user.click(chip("How often it comes back"))
    const repeat = () => panel("How often it comes back")
    await user.click(within(repeat()).getByRole("button", { name: "Every day" }))
    expect(within(repeat()).getByText("Every day.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Weekdays" }))
    expect(within(repeat()).getByText("Every weekday.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Every week" }))
    expect(within(repeat()).getByText("Every week.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Every other week" }))
    expect(within(repeat()).getByText("Every other week.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Every month" }))
    expect(within(repeat()).getByText("Every month.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Once" }))
    expect(within(repeat()).getByText("Once.")).toBeTruthy()
    // Days: Monday, then Wednesday, then Monday off again.
    await user.click(within(repeat()).getByRole("button", { name: "M" }))
    await user.click(within(repeat()).getByRole("button", { name: "W" }))
    expect(within(repeat()).getByText("Every Mon, Wed.")).toBeTruthy()
    expect(chip("How often it comes back").textContent).toBe("Every Mon, Wed")
    await user.click(within(repeat()).getByRole("button", { name: "M" }))
    expect(within(repeat()).getByText("Every Wed.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "After 5 times" }))
    expect(within(repeat()).getByText("Every Wed, 5 times.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Never" }))
    expect(within(repeat()).getByText("Every Wed.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "W" }))
    expect(within(repeat()).getByText("Once.")).toBeTruthy()
    // Times a week: Friday picks the days.
    await user.click(within(repeat()).getByRole("button", { name: "3× a week" }))
    expect(within(repeat()).getByText("3 times a week. Friday picks the days.")).toBeTruthy()
    expect(chip("How often it comes back").textContent).toBe("3× a week")
    await user.click(within(repeat()).getByRole("button", { name: "Times a week" }))
    await user.click(within(repeat()).getByRole("button", { name: "More" }))
    expect(within(repeat()).getByText("4 times a week")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "Fewer" }))
    await user.click(within(repeat()).getByRole("button", { name: "Fewer" }))
    expect(within(repeat()).getByText("2 times a week")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "After 10 times" }))
    expect(within(repeat()).getByText("2 times a week, 10 times. Friday picks the days.")).toBeTruthy()
    await user.click(within(repeat()).getByRole("button", { name: "On days" }))
    // A repeat needs no due: Enter adds it without asking.
    await user.click(line)
    await user.keyboard("{Enter}")
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ text: "water plants", every: "rrule:FREQ=WEEKLY;COUNT=10", per_window: 2 })
  })

  it("clears the line with Escape, and a second Escape leaves it", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add a reading…") as HTMLInputElement
    await user.type(line, "ch 4")
    expect(screen.getByTitle("What sort of work")).toBeTruthy()
    await user.keyboard("{Escape}")
    expect(line.value).toBe("")
    expect(screen.queryByTitle("What sort of work")).toBeNull()
    expect(document.activeElement).toBe(line)
    await user.keyboard("{Escape}")
    expect(document.activeElement).not.toBe(line)
  })

  it("puts a tag section's add in its tag, unless the line names another", async () => {
    const { user } = await todo()
    await user.click(screen.getByRole("button", { name: "View options" }))
    await user.click(screen.getByRole("button", { name: "By tag" }))
    await user.click(screen.getByRole("button", { name: "View options" }))
    const line = await screen.findByLabelText("Add to CHEM 2090…")
    await user.type(line, "titration prelab due tomorrow")
    await waitFor(() => expect(chip("What it belongs to").textContent).toBe("CHEM 2090"))
    await user.keyboard("{Enter}")
    expect((await waitForSent("add")).body).toEqual({ text: "titration prelab due tomorrow", area: "CHEM 2090" })
  })

  it("adds on the Long term list without asking for a due, kept there", async () => {
    const { user } = await todo("/todo?list=Long%20term")
    const line = await screen.findByLabelText("Add anything else…")
    await user.type(line, "learn to weld{Enter}")
    const sent = await waitForSent("add")
    expect(sent.body).toEqual({ text: "learn to weld", long_term: true })
    expect(screen.queryByRole("group", { name: "No due date" })).toBeNull()
    expect(await row("learn to weld")).toBeTruthy()
  })

  it("offers the AI for a line the grammar can't read, and adds what it read", async () => {
    const { user } = await todo()
    const line = screen.getByLabelText("Add anything else…")
    await user.type(line, "zxq blorp wibble frob")
    const ask = await screen.findByRole("button", { name: /Ask AI to read this/ }, { timeout: 5000 })
    await user.click(ask)
    await waitForSent("ask_ai")
    // What it read stands in for the grammar's reading until the line changes, and Add keeps it.
    expect(await screen.findByText(/The AI read this line\. Add to keep it\./, {}, { timeout: 10_000 })).toBeTruthy()
    await user.click(line)
    await user.keyboard("{Enter}")
    const yes = await screen.findByRole("group", { name: "No due date" }).then((g) => within(g).getByRole("button", { name: /Yes, add/ })).catch(() => null)
    if (yes) await user.click(yes)
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ title: expect.any(String) })
    expect(sent.body).not.toHaveProperty("text")
  })

  it("reads typed dues: a time today, a day, a few days off, none, and one it can't read", async () => {
    const { user } = await todo()
    await user.type(screen.getByLabelText("Add anything else…"), "dentist")
    await user.click(chip("When it's due"))
    const due = within(panel("When it's due")).getByRole("textbox", { name: "Due" })
    expect(screen.getByText("No due date yet.")).toBeTruthy()
    await user.type(due, "in 3 days")
    // How far off it says is counted from Friday's day, which runs past midnight: "in 3 or 4 days".
    expect(screen.getByText(/→ Due .* \(in [34] days\) · Enter to set/)).toBeTruthy()
    await user.clear(due)
    await user.type(due, "in 2 hours")
    expect(screen.getByText(/→ Due .* · Enter to set/)).toBeTruthy()
    await user.clear(due)
    await user.type(due, "fri")
    expect(screen.getByText(/→ Due Fri/)).toBeTruthy()
    await user.clear(due)
    await user.type(due, "none")
    expect(screen.getByText(/→ No due date\. Friday fits it in where it costs least\. · Enter to set/)).toBeTruthy()
    await user.clear(due)
    await user.type(due, "dec 3 4pm")
    expect(await screen.findByText(/→ Due Thu 3 Dec, 4pm/, {}, { timeout: 5000 })).toBeTruthy()
    await user.clear(due)
    await user.type(due, "qqqq zzzz")
    expect(await screen.findByText("Can’t read that. Try “fri 5pm” or “oct 30”.", {}, { timeout: 5000 })).toBeTruthy()
    // Escape clears what's typed, then closes nothing more than the text.
    await user.keyboard("{Escape}")
    expect((due as HTMLInputElement).value).toBe("")
    await user.type(due, "oct 30 2027{Enter}")
    await waitFor(() => expect(chip("When it's due").textContent).toMatch(/^Due /), { timeout: 5000 })
  })

  it("sends with Shift-Enter from the due picker, with the due typed there", async () => {
    const { user } = await todo()
    await user.type(screen.getByLabelText("Add anything else…"), "pay rent")
    await user.click(chip("When it's due"))
    const due = within(panel("When it's due")).getByRole("textbox", { name: "Due" })
    await user.type(due, "tomorrow")
    await user.keyboard("{Shift>}{Enter}{/Shift}")
    const sent = await waitForSent("add")
    expect(sent.body).toMatchObject({ text: "pay rent", due: expect.stringMatching(/T23:59$/) })
  })

  it("waits for a typed due the server is still reading, then sets it", async () => {
    const { user } = await todo()
    await user.type(screen.getByLabelText("Add anything else…"), "pick up ring")
    await user.click(chip("When it's due"))
    const due = within(panel("When it's due")).getByRole("textbox", { name: "Due" })
    await user.type(due, "dec 4 3pm{Enter}")
    await waitFor(() => expect(chip("When it's due").textContent).toMatch(/^Due /), { timeout: 5000 })
    expect(friday.base).toMatch(/^http/)
  })
})
